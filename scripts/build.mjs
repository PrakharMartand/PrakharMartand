function btn(key, height = 44) {
  if (links[key].includes("[")) return "";
  return `<a href="${links[key]}"><img src="assets/btn-${key}.svg" height="${height}" alt="${buttons[key].label}"></a>`;
}

function readme() {
  const current = profile.experience.find((e) => e.current);
  const past = profile.experience.filter((e) => !e.current);
  const q = (s) => `'${s.replace(/'/g, "\\'")}'`;
  const config = [
    `// ${profile.handle.toLowerCase()}.config.ts`,
    `export default defineConfig({`,
    `  name: ${q(profile.name)},`,
    `  role: ${q(`${current.role} @ ${current.company}`)},`,
    `  previously: [${past.map((e) => q(`${e.role} @ ${e.company}`)).join(", ")}],`,
    `  projects: [`,
    ...profile.stack.map((g) => `    { name: ${q(g.group.toLowerCase())}, use: [${g.items.map((i) => q(i.name)).join(", ")}] },`),
    `  ],`,
    `  exploring: [`,
    ...profile.focus.map((f) => `    ${q(f)},`),
    `  ],`,
    `  retries: 0, // flaky tests get fixed, not retried`,
    `  reporter: [['list'], ['hire-me', { open: 'always' }]],`,
    `});`,
  ].join("\n");

  const recruiter = `<details>
<summary><b>👔 Recruiter? Here's the 30-second version</b></summary>
<br>

> ${profile.summary}

| | |
|---|---|
| **Role** | ${current.role} @ [${current.company}](${current.url}) |
${past.map((e) => `| **Previously** | ${e.role} @ [${e.company}](${e.url}) |`).join("\n")}
${profile.stack.map((g) => `| **${g.group}** | ${g.items.map((i) => i.name).join(" · ")} |`).join("\n")}
| **Now exploring** | ${profile.focus.join(" · ")} |
| **Contact** | ${[["LinkedIn", links.linkedin], ["Website", links.website], ["Email", links.email], ["Open a hire request", links.hire], ["Printable résumé", links.recruiter]].filter(([, u]) => !u.includes("[")).map(([t, u]) => `[${t}](${u})`).join(" · ")} |

</details>`;
  const developer = `<details>
<summary><b>🧑‍💻 Developer? Read the config</b></summary>
<br>

\`\`\`ts
${config}
\`\`\`

</details>`;
  const head = "<!-- Generated by scripts/build.mjs from profile.json. Edit profile.json, not this file. -->";

  if (theme === "descent") {
    return `${head}
<a href="${links.run}"><img src="assets/descent.svg" width="100%" alt="${profile.name}, ${current.role} at ${current.company}. An animated scene: a flock of starlings spells the name at dusk, a star atlas charts the skills, and repositories drift as glowing jellyfish above a seabed of contributions."></a>

<div align="center">

${btn("run")} ${btn("recruiter")} ${btn("linkedin")} ${btn("website")} ${btn("email")}

</div>

${recruiter}

${developer}

<div align="center">

<sub><i>This profile is alive.</i> The flock is the year's contributions, the constellations are the craft, the ring of months is the year's rhythm,<br>
each jellyfish is a repository (size = stars, glow = recent pushes), and the seabed is every day of work. The moon is tonight's.<br>
Regenerated hourly from live GitHub data. <a href="TEMPLATE.md">Make your own</a>.</sub>

${btn("bug", 40)} ${btn("hire", 40)}

</div>
`;
  }

  return `${head}
<div align="center">

<a href="${links.run}"><img src="assets/hero.svg" width="100%" alt="${profile.name}, ${current.role} at ${current.company}"></a>

${btn("run")} ${btn("recruiter")} ${btn("linkedin")} ${btn("website")} ${btn("email")}

</div>

<br>

<img src="assets/suite.svg" width="100%" alt="${profile.name} test run">

${recruiter}

${developer}

<br>

<img src="assets/stack.svg" width="100%" alt="Tech stack">

<img src="assets/history.svg" width="100%" alt="Contribution history">

<div align="center">

### Found a bug in me?

${btn("bug", 40)} ${btn("hire", 40)}

<sub>This profile is a test suite. It is generated from <a href="profile.json"><code>profile.json</code></a> and re-runs every hour in GitHub Actions.<br>
Fork it, edit one file, and ship your own. See <a href="TEMPLATE.md"><code>TEMPLATE.md</code></a>.</sub>

</div>
`;
}

function demoData() {
  const weeks = [];
  const start = Date.UTC(2025, 8, 21);
  for (let w = 0; w < 53; w++) {
    const days = [];
    for (let d = 0; d < 7; d++) {
      const i = w * 7 + d;
      const v = Math.max(0, Math.round(Math.sin(i / 9) * 4 + Math.sin(i / 2.3) * 3 + (i % 11 === 0 ? -6 : 1)));
      days.push({ date: new Date(start + i * 864e5).toISOString().slice(0, 10), count: v });
    }
    weeks.push(days);
  }
  return {
    fetchedAt: new Date().toISOString(),
    contributions: weeks.flat().reduce((a, d) => a + d.count, 0),
    longestStreak: 23, currentStreak: 6, repos: 18, stars: 41, followers: 57, pullRequests: 212,
    repoList: [
      { name: "SkillMeUp", stars: 2, lang: "TypeScript", color: "#3178c6", activity: 0.95 },
      { name: "PrakharMartand", stars: 0, lang: "JavaScript", color: "#f1e05a", activity: 1 },
      { name: "P7Martand", stars: 0, lang: "JavaScript", color: "#f1e05a", activity: 0.35 },
      { name: "OpenSourceHarness", stars: 0, lang: "TypeScript", color: "#3178c6", activity: 0.25 },
      { name: "reproRepo", stars: 0, lang: "Python", color: "#3572A5", activity: 0.5 },
    ],
    languages: [
      { name: "TypeScript", color: "#3178c6", pct: 41.2 }, { name: "JavaScript", color: "#f1e05a", pct: 22.5 },
      { name: "Java", color: "#b07219", pct: 14.1 }, { name: "Python", color: "#3572A5", pct: 12.9 },
      { name: "HTML", color: "#e34c26", pct: 5.8 }, { name: "CSS", color: "#563d7c", pct: 3.5 },
    ],
    weeks,
  };
}
