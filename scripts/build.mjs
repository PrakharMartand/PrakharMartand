import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadGithub } from "./github.mjs";
import { loadIcons } from "./icons.mjs";
import { descentSvg } from "./descent.mjs";
import { C, buttonSvg, heroSvg, historySvg, resolveSpec, stackSvg, suiteSvg } from "./svg.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const at = (...p) => join(root, ...p);

const profile = JSON.parse(await readFile(at("profile.json"), "utf8"));
await mkdir(at("assets"), { recursive: true });
await mkdir(at("data"), { recursive: true });

// In Actions the repository decides whose profile this is, so a copied repo never shows the original author's data.
const repoSlug = process.env.GITHUB_REPOSITORY ?? `${profile.handle}/${profile.handle}`;
const [repoOwner, repoName] = repoSlug.split("/");
if (repoOwner.toLowerCase() !== profile.handle.toLowerCase()) {
  console.warn(`profile.json handle "${profile.handle}" doesn't match repo owner "${repoOwner}"; using "${repoOwner}". Update "handle" in profile.json.`);
  profile.handle = repoOwner;
}
const pagesSite = `https://${repoOwner.toLowerCase()}.github.io/${repoName}/`;
if (!profile.site || (profile.site.includes(".github.io") && !profile.site.includes(`//${repoOwner.toLowerCase()}.github.io`))) {
  profile.site = pagesSite;
}

const gh = process.env.DEMO ? demoData() : await loadGithub(profile.handle, at("data/github.json"));
const slugs = profile.stack.flatMap((g) => g.items.map((i) => i.icon)).filter(Boolean);
const icons = await loadIcons(slugs, at("data/icons.json"));
const runDate = gh?.fetchedAt ? gh.fetchedAt.slice(0, 10) : "awaiting first CI run";

const repo = `https://github.com/${repoSlug}`;
const links = {
  run: profile.site,
  recruiter: `${profile.site}#recruiter`,
  linkedin: profile.links.linkedin,
  website: profile.links.website,
  email: `mailto:${profile.links.email}`,
  hire: `${repo}/issues/new?template=hire.yml`,
  bug: `${repo}/issues/new?template=bug.yml`,
};

const buttons = {
  run: { label: "Run me live", glyph: "▶", accent: C.green, primary: true },
  recruiter: { label: "Recruiter mode", glyph: "◧", accent: C.blue },
  linkedin: { label: "LinkedIn", glyph: "in", accent: "#0A84FF" },
  website: { label: "Website", glyph: "⌘", accent: C.cyan },
  email: { label: "Email", glyph: "@", accent: C.amber },
  hire: { label: "Feature request: hire me", glyph: "+", accent: C.green },
  bug: { label: "File a bug against me", glyph: "!", accent: C.red },
};

const theme = profile.theme === "spec" ? "spec" : "descent";
if (theme === "descent") {
  Object.assign(buttons.run, { label: "Explore interactively" });
  Object.assign(buttons.recruiter, { label: "Résumé" });
  Object.assign(buttons.hire, { label: "Hire me" });
  Object.assign(buttons.bug, { label: "Leave feedback" });
}

const files = {
  ...(theme === "descent"
    ? { "assets/descent.svg": descentSvg(profile, gh) }
    : {
        "assets/hero.svg": heroSvg(profile),
        "assets/suite.svg": suiteSvg(profile, gh, runDate),
        "assets/stack.svg": stackSvg(profile, icons),
        "assets/history.svg": historySvg(gh),
      }),
  ...Object.fromEntries(Object.entries(buttons).map(([k, b]) => [`assets/btn-${k}.svg`, buttonSvg(b, theme)])),
  "README.md": readme(),
  "docs/index.html": pageHead(await readFile(at("docs/index.html"), "utf8")),
  ".github/ISSUE_TEMPLATE/hire.yml": hireForm(),
  ".github/ISSUE_TEMPLATE/bug.yml": bugForm(),
  "docs/data.js": `// generated by scripts/build.mjs from profile.json\nwindow.PROFILE = ${JSON.stringify(
    {
      ...profile,
      github: gh ? { ...gh, weeks: undefined } : null,
      suite: resolveSpec(profile, gh),
      icons: Object.fromEntries(slugs.filter((s) => icons[s]).map((s) => [s, icons[s]])),
      links,
      runDate,
    },
    null,
    2,
  )};\n`,
};

for (const [path, content] of Object.entries(files)) {
  await mkdir(dirname(at(path)), { recursive: true });
  await writeFile(at(path), content);
}
console.log(`built ${Object.keys(files).length} files · github data: ${gh ? runDate : "none"}`);

function pageHead(html) {
  const e = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
  const title = e(`${profile.name} · readme.spec`);
  const desc = e(`${profile.name}, ${profile.title}. A profile you can run like a test suite.`);
  return html
    .replace(/<title>[^<]*<\/title>/, `<title>${title}</title>`)
    .replace(/(<meta name="description" content=")[^"]*/, `$1${desc}`)
    .replace(/(<meta property="og:title" content=")[^"]*/, `$1${title}`);
}

function firstName() {
  return profile.name.split(" ")[0];
}

function yamlStr(s) {
  return JSON.stringify(s);
}

